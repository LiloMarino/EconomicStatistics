def _month(index: int) -> date:
    return date(FIRST_MONTH.year + index // 12, index % 12 + 1, 1)


def seed_ipca(session: Session) -> None:
    for series_id, values in IPCA_MONTHLY.items():
        upsert_observations(
            session,
            series_id,
            [Observation(ref_date=_month(i), value=v) for i, v in enumerate(values)],
        )
    upsert_observations(
        session,
        SeriesId.INFLATION_TARGET,
        [
            Observation(ref_date=date(year, 1, 1), value=value)
            for year, value in INFLATION_TARGET.items()
        ],
    )
    session.commit()
